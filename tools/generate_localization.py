#!/usr/bin/env python3
"""Generate immutable Windows-1251 UI strings; user data never enters this catalog."""
from pathlib import Path
import json
import subprocess
root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'localization/ru.json').read_text())
def literal(value):
    return '"' + ''.join('\\%03o' % b for b in value.encode('cp1251')) + '"'
lines = ['#pragma once', '', '// Generated by tools/generate_localization.py from localization/ru.json.',
         '// Values are font bytes, not UTF-8: do not pass them to Applet::parse.',
         'namespace NicheGraphics::InkHUD {',
         '#if defined(HELTEC_VISION_MASTER_E290)',
         'struct Translation { const char *english; const char *russian; };',
         'inline constexpr Translation translations[] = {']
for en, ru in catalog.items():
    lines.append('    {' + json.dumps(en) + ', ' + literal(ru) + '}, // ' + ru.replace('\n', ' / '))
lines += ['};', 'constexpr bool sameText(const char *a, const char *b) {',
          '    while (*a && *a == *b) { ++a; ++b; }', '    return *a == *b;', '}',
          'constexpr const char *translate(const char *text) {', '    if (!text) return "";',
          '    for (const auto &entry : translations)',
          '        if (sameText(text, entry.english)) return entry.russian;',
          '    return text;', '}', '#else',
          'constexpr const char *translate(const char *text) { return text; }', '#endif', '}',
          '#define INKHUD_TEXT(text) NicheGraphics::InkHUD::translate(text)', '']
(root / 'firmware/src/graphics/niche/InkHUD/Localization.h').write_text('\n'.join(lines))
print(f'Generated {len(catalog)} translations')

formatter = root / ".venv/bin/clang-format"
if formatter.exists():
    subprocess.run([str(formatter), "-i", "--style=file:" + str(root / "firmware/.trunk/configs/.clang-format"),
                    str(root / "firmware/src/graphics/niche/InkHUD/Localization.h")], check=True)
